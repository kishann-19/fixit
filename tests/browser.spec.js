import {test,expect} from '@playwright/test';
test('User report, follow-up, authority resolution, and responsive layouts',async({page})=>{
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('/');await page.getByRole('button',{name:'Explore user demo'}).click();
await expect(page.getByRole('heading',{name:'Campus at a glance'})).toBeVisible();
await expect(page.locator('.report-row')).toHaveCount(5);
await page.screenshot({path:'artifacts/dashboard-desktop.png',fullPage:true});
await page.getByRole('button',{name:'Report an issue',exact:true}).first().click();
await page.getByLabel('Issue title').fill('Library classroom light fixture');
await page.getByLabel('Category',{exact:true}).selectOption('Electrical');
await page.getByLabel('Location',{exact:true}).selectOption('1');
await page.getByLabel('Description',{exact:true}).fill('The light beside the classroom entrance is flickering.');
await page.getByRole('button',{name:'Submit report'}).click();
await page.getByRole('button').filter({hasText:'Library classroom light fixture'}).click();
await expect(page.getByText('Authority controls')).toHaveCount(0);
await page.getByLabel('Add an update').fill('Please check before the afternoon lecture.');await page.getByRole('button',{name:'Post update'}).click();
await expect(page.getByText('Please check before the afternoon lecture.',{exact:true})).toBeVisible();
await page.getByRole('button',{name:'Close dialog'}).click();
await page.getByLabel('Search reports').fill('no report matches this query');await expect(page.getByText('No reports found')).toBeVisible();
await page.getByRole('button',{name:'Clear filters'}).click();
await page.setViewportSize({width:390,height:844});await page.screenshot({path:'artifacts/dashboard-mobile.png',fullPage:true});
expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
await page.getByRole('button',{name:'Sign out'}).click();await page.getByRole('button',{name:'Authority portal'}).click();await page.getByRole('button',{name:'Explore authority demo'}).click();
await page.getByRole('button').filter({hasText:'Library classroom light fixture'}).click();
await page.getByLabel('Status',{exact:true}).selectOption('Resolved');await page.getByLabel('Priority',{exact:true}).selectOption('High');await page.getByRole('button',{name:'Save progress'}).click();
await expect(page.locator('.detail-meta .badge')).toHaveText('Resolved');
await page.getByRole('button',{name:'Close dialog'}).click();
await page.getByRole('button',{name:'Toggle navigation'}).click();await page.getByRole('button',{name:'Campus spaces',exact:true}).click();await expect(page.locator('.location-card')).toHaveCount(90);
await page.getByLabel('Space type').selectOption('Washroom');await expect(page.locator('.location-card')).toHaveCount(20);
expect(errors).toEqual([]);
});
